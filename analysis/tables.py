"""Results tables and number macros for the report, generated from summary.csv.

Module: tables.py
Owner: M5
Inputs:  results/summary.csv (written by experiments/run_experiments.py).
Outputs: report/generated/results_macros.tex  - every result number as a macro
         report/generated/tab_*.tex            - LaTeX tables used in Section 9
         results/summary_table.md              - the same numbers for README/slides

In the report a number is written as \\R{E2}{improved}{path_rmse_m}, never typed by hand,
so the text always matches the latest experiment run. Aggregates over seeds use the
keys mean_<metric>, std_<metric>, success_count and runs.
"""

import math
import os
import sys

import pandas as pd

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
GEN = os.path.join(REPO, "report", "generated")
METHODS = ("baseline", "improved")
NAMES = {"baseline": "Method A", "improved": "Method B"}

# metric -> (decimals, unit shown in tables)
FORMAT = {
    "path_rmse_m": (3, "m"), "path_max_err_m": (3, "m"), "mission_time_s": (1, "s"),
    "max_tilt_deg": (1, "deg"), "control_effort": (1, ""), "waypoints_reached": (0, ""),
    "step1_rise_time_s": (2, "s"), "step1_overshoot_pct": (1, "%"),
    "step1_settling_time_s": (1, "s"), "step1_ss_error_m": (3, "m"),
    "step2_rise_time_s": (2, "s"), "step2_overshoot_pct": (1, "%"),
    "step2_settling_time_s": (1, "s"), "step2_ss_error_m": (3, "m"),
}


def fmt(value, decimals: int) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "--"
    if isinstance(value, (bool,)) or str(value) in ("True", "False"):
        return "yes" if str(value) == "True" else "no"
    return f"{float(value):.{decimals}f}"


def macro(key: str, value: str) -> str:
    return f"\\expandafter\\def\\csname R:{key}\\endcsname{{{value}}}\n"


def build_macros(df: pd.DataFrame) -> str:
    out = ["% Generated by analysis/tables.py from results/summary.csv - do not edit.\n",
           "\\providecommand{\\R}[3]{\\csname R:#1:#2:#3\\endcsname}\n"]
    for (sc, method), g in df[df.tag.fillna("") == ""].groupby(["scenario", "method"]):
        key = f"{sc}:{method}"
        out.append(macro(f"{key}:runs", str(len(g))))
        out.append(macro(f"{key}:success_count", str(int(g.success.astype(bool).sum()))))
        out.append(macro(f"{key}:crash_count", str(int(g.crashed.astype(bool).sum()))))
        for metric, (dec, _) in FORMAT.items():
            if metric not in g:
                continue
            col = pd.to_numeric(g[metric], errors="coerce")
            if len(g) == 1:
                out.append(macro(f"{key}:{metric}", fmt(col.iloc[0], dec)))
            out.append(macro(f"{key}:mean_{metric}", fmt(col.mean(), dec)))
            out.append(macro(f"{key}:std_{metric}", fmt(col.std(ddof=1) if len(g) > 1 else 0.0, dec)))
    # improvements of B over A for single-run scenarios (percent reduction)
    for sc in df.scenario.unique():
        a = df[(df.scenario == sc) & (df.method == "baseline") & (df.tag.fillna("") == "")]
        b = df[(df.scenario == sc) & (df.method == "improved") & (df.tag.fillna("") == "")]
        if a.empty or b.empty:
            continue
        for metric in ("path_rmse_m", "control_effort", "max_tilt_deg", "mission_time_s"):
            if metric in a and a[metric].notna().all() and b[metric].notna().all():
                va, vb = a[metric].mean(), b[metric].mean()
                if va:
                    out.append(macro(f"{sc}:reduction:{metric}", f"{100 * (va - vb) / va:.0f}"))
    # whole-scenario summaries usable in text: success "k/n" and failed sweep values
    for (sc, method), g in df.groupby(["scenario", "method"]):
        out.append(macro(f"{sc}:{method}:success", value_for(df, f"{sc}:{method}:success")))
        if g.tag.fillna("").ne("").any():
            out.append(macro(f"{sc}:{method}:failed_gains", value_for(df, f"{sc}:{method}:failed_gains")))
    # sweep values (E6)
    for _, r in df[df.tag.fillna("") != ""].iterrows():
        param, val = r.tag.split("=")
        key = f"{r.scenario}:{r.method}:{param}{val}"
        out.append(macro(f"{key}:success", "yes" if bool(r.success) else "no"))
        out.append(macro(f"{key}:path_rmse_m", fmt(r.path_rmse_m, 3)))
    return "".join(out)


def table(rows, header, caption, label, col_spec) -> str:
    lines = ["\\begin{table}[h]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             f"\\begin{{tabular}}{{{col_spec}}}", "\\hline",
             " & ".join(f"\\textbf{{{h}}}" for h in header) + " \\\\ \\hline"]
    lines += [" & ".join(r) + " \\\\ \\hline" for r in rows]
    lines += ["\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def single(df, sc, method, metric):
    g = df[(df.scenario == sc) & (df.method == method) & (df.tag.fillna("") == "")]
    return fmt(pd.to_numeric(g[metric], errors="coerce").mean(), FORMAT[metric][0]) if len(g) else "--"


def build_tables(df: pd.DataFrame) -> dict:
    t = {}
    rows = []
    for step, label in (("step1", "Take-off 0.1 m $\\to$ 2.0 m"), ("step2", "Step 2.0 m $\\to$ 1.0 m")):
        for metric, name in (("rise_time_s", "Rise time 10--90\\% (s)"), ("overshoot_pct", "Overshoot (\\%)"),
                             ("settling_time_s", "Settling time, 2\\% band (s)"),
                             ("ss_error_m", "Steady-state error (m)")):
            rows.append([f"{label}: {name}"] + [single(df, "E1", m, f"{step}_{metric}") for m in METHODS])
    t["tab_e1"] = table(rows, ["Metric", "Method A", "Method B"],
                        "E1 altitude step response (true altitude)", "tab:e1", "|p{8.2cm}|c|c|")
    rows = []
    for sc, name in (("E2", "E2 square"), ("E3", "E3 3D")):
        for metric, label in (("path_rmse_m", "Path RMSE (m)"), ("path_max_err_m", "Max path error (m)"),
                              ("mission_time_s", "Mission time (s)"), ("max_tilt_deg", "Peak tilt (deg)"),
                              ("control_effort", "Control effort ((rad/s)$^2$)")):
            rows.append([f"{name}: {label}"] + [single(df, sc, m, metric) for m in METHODS])
    t["tab_e2e3"] = table(rows, ["Metric", "Method A", "Method B"],
                          "Waypoint missions without disturbance (E2, E3)", "tab:e2e3", "|p{8.2cm}|c|c|")
    rows = []
    for metric, label in (("waypoints_reached", "Waypoints reached (of 5)"),
                          ("path_rmse_m", "Path RMSE (m)"), ("path_max_err_m", "Max path error (m)"),
                          ("mission_time_s", "Mission time (s)"), ("max_tilt_deg", "Peak tilt (deg)")):
        rows.append([label] + [single(df, "E4", m, metric) for m in METHODS])
    t["tab_e4"] = table(rows, ["E4 metric (wind 0.3 N + 0.15 N gusts)", "Method A", "Method B"],
                        "Square mission under crosswind (E4)", "tab:e4", "|p{8.2cm}|c|c|")
    rows = []
    e5 = df[df.scenario == "E5"]
    if not e5.empty:
        for m in METHODS:
            g = e5[e5.method == m]
            ok = g[g.success.astype(bool)]
            rows.append([NAMES[m], f"{int(g.success.astype(bool).sum())}/{len(g)}",
                         f"{ok.path_rmse_m.mean():.3f} $\\pm$ {ok.path_rmse_m.std(ddof=1):.3f}" if len(ok) > 1 else "--",
                         f"{ok.mission_time_s.mean():.1f} $\\pm$ {ok.mission_time_s.std(ddof=1):.1f}" if len(ok) > 1 else "--",
                         f"{ok.max_tilt_deg.mean():.1f}" if len(ok) else "--"])
        t["tab_e5"] = table(rows, ["Method", "Success", "Path RMSE (m)", "Mission time (s)", "Peak tilt (deg)"],
                            "Sensor-noise robustness over ten seeds (E5, mean $\\pm$ std of successful runs)",
                            "tab:e5", "|l|c|c|c|c|")
    e6 = df[df.scenario == "E6"].copy()
    if not e6.empty:
        e6["kp"] = e6.tag.str.split("=").str[1].astype(float)
        rows = []
        for kp in sorted(e6.kp.unique()):
            cells = [f"{kp:g}"]
            for m in METHODS:
                r = e6[(e6.kp == kp) & (e6.method == m)]
                if r.empty:
                    cells.append("--")
                elif bool(r.success.iloc[0]):
                    cells.append(f"success, RMSE {r.path_rmse_m.iloc[0]:.3f} m")
                else:
                    cells.append("crashed" if bool(r.crashed.iloc[0]) else "did not finish")
            rows.append(cells)
        t["tab_e6"] = table(rows, ["Roll $K_p$", "Method A", "Method B"],
                            "Roll-gain sensitivity on the square mission (E6)", "tab:e6", "|c|c|c|")
    return t


def markdown(df: pd.DataFrame) -> str:
    cols = ["scenario", "method", "seed", "tag", "success", "crashed", "path_rmse_m",
            "mission_time_s", "max_tilt_deg", "control_effort"]
    cols = [c for c in cols if c in df]
    d = df[cols].copy()
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in d.iterrows():
        lines.append("| " + " | ".join(fmt(v, 3) if isinstance(v, float) else str(v) for v in r) + " |")
    return "# Results summary (generated)\n\n" + "\n".join(lines) + "\n"


def value_for(df: pd.DataFrame, key: str) -> str:
    """Resolve a placeholder 'SCENARIO:method:metric' to a formatted number.

    Special metrics: 'success' -> 'k/n', 'failed_gains' -> comma list of sweep values
    that failed (or 'none').
    """
    sc, method, metric = key.split(":")
    g = df[(df.scenario == sc) & (df.method == method)]
    if g.empty:
        raise KeyError(f"no runs for {sc}/{method}")
    if metric == "success":
        return f"{int(g.success.astype(bool).sum())}/{len(g)}"
    if metric == "failed_gains":
        bad = g[~g.success.astype(bool)].tag.str.split("=").str[1].tolist()
        return ", ".join(bad) if bad else "none"
    dec = FORMAT.get(metric, (3, ""))[0]
    return fmt(pd.to_numeric(g[metric], errors="coerce").mean(), dec)


def render_template(df: pd.DataFrame, src: str, dst: str) -> None:
    """Fill {{SC:method:metric}} placeholders in a text file from the results."""
    import re
    with open(src, "r", encoding="utf-8") as f:
        text = f.read()
    filled = re.sub(r"\{\{([^}]+)\}\}", lambda m: value_for(df, m.group(1).strip()), text)
    header = ("<!-- Generated by analysis/tables.py from docs/video_script.template.md and "
              "results/summary.csv. Edit the template, not this file. -->\n")
    with open(dst, "w", encoding="utf-8") as f:
        f.write(header + filled)


def main() -> None:
    df = pd.read_csv(os.path.join(REPO, "results", "summary.csv"))
    template = os.path.join(REPO, "docs", "video_script.template.md")
    if os.path.exists(template):
        render_template(df, template, os.path.join(REPO, "docs", "video_script.md"))
    os.makedirs(GEN, exist_ok=True)
    with open(os.path.join(GEN, "results_macros.tex"), "w", encoding="utf-8") as f:
        f.write(build_macros(df))
    for name, tex in build_tables(df).items():
        with open(os.path.join(GEN, f"{name}.tex"), "w", encoding="utf-8") as f:
            f.write(tex)
    with open(os.path.join(REPO, "results", "summary_table.md"), "w", encoding="utf-8") as f:
        f.write(markdown(df))
    print(f"  macros and tables for {len(df)} runs -> {os.path.relpath(GEN, REPO)}")


if __name__ == "__main__":
    sys.exit(main())
