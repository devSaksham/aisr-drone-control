"""Gain tuning harness: run a scenario with gain overrides and log the metrics.

Module: tune.py
Owner: M5
Inputs:  scenario id, method, one or more gain override sets (key=value).
Outputs: results/tuning/<scenario>/<method>/<tag>/ telemetry, a line per trial in
         docs/tuning_log.md (date, scenario, method, overrides, key metrics).

Examples:
    python experiments/tune.py E1 improved alt_kp=6 alt_kd=4
    python experiments/tune.py E2 baseline pos_kp=0.8 --note "less aggressive"
Every trial is kept in the log, including the ones that made things worse, so the
tuning process can be shown in the report (Section 7).
"""

import argparse
import datetime as dt
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, REPO)

from analysis.metrics import load_run  # noqa: E402
from experiments.run_experiments import load_scenarios, run_single  # noqa: E402

LOG = os.path.join(REPO, "docs", "tuning_log.md")
KEY_METRICS = ["success", "crashed", "max_tilt_deg", "control_effort",
               "step1_overshoot_pct", "step1_settling_time_s", "step1_ss_error_m",
               "step2_overshoot_pct", "step2_settling_time_s", "step2_ss_error_m",
               "path_rmse_m", "path_max_err_m", "mission_time_s"]


def parse_overrides(pairs):
    out = {}
    for p in pairs:
        k, v = p.split("=", 1)
        out[k] = float(v)
    return out


def fmt(v):
    if isinstance(v, float):
        return f"{v:.3g}"
    return str(v)


def trial(scenario_id: str, method: str, overrides: dict, seed: int = 0, note: str = ""):
    sc = load_scenarios([scenario_id])[0]
    sc.setdefault("gains", {})[method] = overrides
    tag = "_".join(f"{k}{v:g}" for k, v in overrides.items()) or "default"
    out_rel = os.path.join("results", "tuning", scenario_id, method, f"{tag}_s{seed}")
    run_single(sc, method, seed, out_rel)
    m = load_run(os.path.join(REPO, out_rel)) or {}
    shown = {k: m[k] for k in KEY_METRICS if k in m and m[k] == m[k]}
    print("   " + "  ".join(f"{k}={fmt(v)}" for k, v in shown.items()))
    new = not os.path.exists(LOG)
    with open(LOG, "a", encoding="utf-8") as f:
        if new:
            f.write("# Tuning log\n\nGenerated by `experiments/tune.py`; one line per trial.\n\n"
                    "| Date | Scenario | Method | Overrides | Metrics | Note |\n|---|---|---|---|---|---|\n")
        ov = ", ".join(f"{k}={v:g}" for k, v in overrides.items()) or "defaults"
        ms = "; ".join(f"{k}={fmt(v)}" for k, v in shown.items())
        f.write(f"| {dt.datetime.now():%Y-%m-%d %H:%M} | {scenario_id} | {method} | {ov} | "
                f"{ms} | {note} |\n")
    return m


def main() -> None:
    ap = argparse.ArgumentParser(description="Run one tuning trial")
    ap.add_argument("scenario")
    ap.add_argument("method", choices=["baseline", "improved"])
    ap.add_argument("overrides", nargs="*", help="gain=value pairs")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--note", default="")
    a = ap.parse_args()
    trial(a.scenario, a.method, parse_overrides(a.overrides), a.seed, a.note)


if __name__ == "__main__":
    main()
