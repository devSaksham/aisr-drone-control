"""Count the pages each member wrote, for the Writing Allocation table.

Owner: M1 (report assembly)
Input:  report/report.toc from a previous LaTeX build.
Output: report/generated/pages.tex defining \\pagesMone ... \\pagesMfive.

A section's length is (start page of the next section) - (its start page); a section
that starts mid-page is counted as the difference, so lengths are approximate to
about half a page. The Abstract counts as one page. Run between two LaTeX passes
(`make report` does this).
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OWNERS = {  # section titles as they appear in the Index -> member slot
    "Abstract": "Mone", "Introduction": "Mone", "Problem Statement and Objectives": "Mone",
    "References": "Mone",
    "Literature and Industry Review": "Mtwo", "Novelty": "Mtwo",
    "Syllabus Mapping and Theory": "Mthree", "System Design": "Mthree",
    "Methodology and Algorithms": "Mfour", "Simulation Setup": "Mfour",
    "Results and Analysis": "Mfive", "Conclusion and Future Scope": "Mfive",
    "Appendix: Links and Logs": "Mfive",
}


def owned_starts_mid(page: int, owned) -> bool:
    """Assume a page whose first entry is a subsection/section also holds the tail of the
    previous entry, unless it is the very first page of the main text."""
    return page != owned[0][1]


def main() -> None:
    toc = os.path.join(HERE, "report.toc")
    if not os.path.exists(toc):
        return
    entries = []
    pat = re.compile(r"\\contentsline \{(section|subsection)\}\{(?:\\numberline \{[^}]*\})?([^}]*)\}\{([^}]*)\}")
    with open(toc, encoding="utf-8", errors="ignore") as f:
        for line in f:
            m = pat.search(line)
            if m:
                entries.append((m.group(1), m.group(2).strip(), m.group(3).strip()))
    # owner of every main-matter entry: its own title, else the enclosing section's owner
    owned, current = [], None
    for level, title, page in entries:
        if not page.isdigit():
            continue
        if level == "section":
            current = OWNERS.get(title)
        owned.append((OWNERS.get(title, current), int(page)))
    totals = {k: 0.0 for k in set(OWNERS.values())}
    totals["Mone"] += 1.0  # Abstract (front matter, roman numbered)
    if not owned:
        return
    # Walk page by page: a page is shared equally by the writers whose text is on it
    # (whoever continues from the previous page plus everyone starting on it).
    last_page = owned[-1][1]
    carry = None
    for page in range(owned[0][1], last_page + 1):
        starting = [o for o, p in owned if p == page]
        on_page = ([carry] if carry and (not starting or owned_starts_mid(page, owned)) else []) + starting
        writers = [w for w in on_page if w]
        for w in writers:
            totals[w] += 1.0 / len(writers)
        if starting:
            carry = starting[-1]
    os.makedirs(os.path.join(HERE, "generated"), exist_ok=True)
    with open(os.path.join(HERE, "generated", "pages.tex"), "w", encoding="utf-8") as f:
        f.write("% Generated by report/page_counts.py from report.toc\n")
        for key, val in sorted(totals.items()):
            f.write(f"\\renewcommand{{\\pages{key}}}{{{round(val * 2) / 2:g}}}\n")
    print("  pages per member:", {k: v for k, v in sorted(totals.items())})


if __name__ == "__main__":
    main()
